using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace RDCore.Runtime.Generators;

/// <summary>
/// Generates the invoker of each member of the standard library's declarations (IR lowering S1.9): a call of the interface method itself, its arguments
/// cast to the types it declares, in place of a reflected invocation.
/// </summary>
/// <remarks>
/// A member is found by the key the symbol reader stamps on it - its interface's name, its own and its arity, which no two members of one interface share -
/// so the generated table is keyed the same way. A member whose call cannot be written here (one that returns no result, or takes an argument by
/// reference) has no invoker, and is invoked by reflection as before. The code is generated only into a compilation that declares the table's type.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class StdLibInvokerGenerator : IIncrementalGenerator
{
    private const string DeclarationsNamespace = "RDCore.SDK.Runtime.Abstract.StdLib";
    private const string InvokersType = "RDCore.Runtime.StdLib.StdLibInvokers";
    private const string ResultNamespace = "RDCore.SDK.Runtime.Shared";
    private const string ResultName = "RuntimeSemanticsEvaluationResult";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var source = context.CompilationProvider.Select((compilation, _) => compilation.GetTypeByMetadataName(InvokersType) is null ? null : Generate(compilation));
        context.RegisterSourceOutput(source, (output, text) =>
        {
            if (text is not null)
            {
                output.AddSource("StdLibInvokers.g.cs", text);
            }
        });
    }

    private static string Generate(Compilation compilation)
    {
        var entries = new List<(string Key, string Invoker)>();
        if (NamespaceOf(compilation.GlobalNamespace, DeclarationsNamespace) is { } declarations)
        {
            foreach (var declaration in declarations.GetTypeMembers().Where(type => type.TypeKind == TypeKind.Interface && type.Name.StartsWith("IStd")))
            {
                foreach (var method in declaration.GetMembers().OfType<IMethodSymbol>())
                {
                    if (InvokerOf(declaration, method) is { } invoker)
                    {
                        entries.Add(($"{declaration.Name}.{method.Name}/{method.Parameters.Length}", invoker));
                    }
                }
            }
        }

        var text = new StringBuilder();
        text.AppendLine("// <auto-generated/>");
        text.AppendLine("#nullable enable");
        text.AppendLine();
        text.AppendLine("namespace RDCore.Runtime.StdLib;");
        text.AppendLine();
        text.AppendLine("internal static partial class StdLibInvokers");
        text.AppendLine("{");
        text.AppendLine("    public static partial StdLibInvoker? For(string target) => target switch");
        text.AppendLine("    {");

        // two members of one interface with the same key cannot be told apart: neither is given an invoker, and the dispatcher refuses the declaration.
        foreach (var entry in entries.GroupBy(entry => entry.Key).Where(group => group.Count() == 1).Select(group => group.Single()).OrderBy(entry => entry.Key, System.StringComparer.Ordinal))
        {
            text.Append("        \"").Append(entry.Key).Append("\" => ").Append(entry.Invoker).AppendLine(",");
        }

        text.AppendLine("        _ => null,");
        text.AppendLine("    };");
        text.AppendLine("}");
        return text.ToString();
    }

    // the call of a member through its interface, its arguments cast from what the dispatcher marshalled each to: a value of the parameter's type, or null for
    // one left out - which is a value type's default, as a reflected invocation passes it.
    private static string? InvokerOf(INamedTypeSymbol declaration, IMethodSymbol method)
    {
        if (method.MethodKind != MethodKind.Ordinary || method.IsStatic || method.IsGenericMethod
            || method.Parameters.Any(parameter => parameter.RefKind != RefKind.None)
            || method.ReturnType is not INamedTypeSymbol { Name: ResultName } returned || returned.ContainingNamespace.ToDisplayString() != ResultNamespace)
        {
            return null;
        }

        var arguments = method.Parameters.Select((parameter, index) => ArgumentOf(parameter.Type, index));
        var call = $"(({declaration.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)})implementation).{Identifier(method.Name)}({string.Join(", ", arguments)})";
        return $"static (implementation, arguments) => {(returned.IsGenericType ? $"Of({call})" : call)}";
    }

    private static string ArgumentOf(ITypeSymbol type, int index)
    {
        var name = type.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        return type switch
        {
            { IsValueType: true, OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } => $"({name})arguments[{index}]",
            { IsValueType: true } => $"({name})(arguments[{index}] ?? default({name}))",
            _ => $"({name})arguments[{index}]!",
        };
    }

    private static string Identifier(string name) => SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;

    private static INamespaceSymbol? NamespaceOf(INamespaceSymbol root, string name)
    {
        var current = root;
        foreach (var part in name.Split('.'))
        {
            current = current.GetNamespaceMembers().FirstOrDefault(member => member.Name == part);
            if (current is null)
            {
                return null;
            }
        }

        return current;
    }
}
